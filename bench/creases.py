"""Do the creases bring the subdivided mesh closer to the source?

    blender -b --factory-startup --python bench/creases.py -- [--models a,b] [--targets 1000,3000] [--levels 2]

Blender script. For each model it remeshes the source with the add-on (the
engine as Blender calls it), subdivides the result with a Subdivision Surface
modifier, once with the crease weights and once without, and measures both
against the source with `openclare measure`. Writes
bench/results/CREASES.md. Needs `make addon` and a release build.
"""

import argparse
import json
import resource
import sys
from pathlib import Path

import bpy

BENCH = Path(__file__).resolve().parent
sys.path.insert(0, str(BENCH))
sys.path.insert(0, str(BENCH.parent / "blender"))
import openclare  # noqa: E402
from blender_io import read_obj, write_obj  # noqa: E402
from run import AUTHORED, MEMORY_CAP, MODELS, OPENCLARE, OUTPUT, RESULTS, available_models, run, source_path  # noqa: E402

# The engine runs inside this Blender: the cap of the bench on the memory of
# what it starts is put on this process itself.
resource.setrlimit(resource.RLIMIT_AS, (MEMORY_CAP, resource.getrlimit(resource.RLIMIT_AS)[1]))


def measured(source, mesh):
    done = run([OPENCLARE, "measure", source, mesh, "--json"])
    return json.loads(done.stdout) if done.returncode == 0 else None


def subdivided(quads, levels, path):
    """Writes `quads`, an object, subdivided `levels` times as Blender does it."""
    evaluated = quads.evaluated_get(bpy.context.evaluated_depsgraph_get())
    mesh = evaluated.to_mesh()
    write_obj(path, mesh)
    evaluated.to_mesh_clear()


def main():
    arguments = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    # Not by default: two models of hundreds of pieces, and the scenes made by
    # hand, which are more than a mesh (this script reads the mesh alone).
    left_out = {"mahaveer", "marine"} | AUTHORED
    parser.add_argument("--models", default=",".join(m for m in available_models() if m not in left_out))
    parser.add_argument("--targets", default="1000,3000")
    parser.add_argument("--levels", type=int, default=2)
    options = parser.parse_args(arguments)
    wanted = options.models.split(",")
    targets = [int(t) for t in options.targets.split(",")]

    lines = [
        "# Creases",
        "",
        "Does a crease weight on the edges that should stay sharp bring the subdivided mesh closer to",
        f"the source? Each mesh is subdivided {options.levels} times by Blender's Subdivision Surface modifier, with",
        "the weights the engine gave and without, and both are measured against the source.",
        "Generated by `bench/creases.py`.",
        "",
        "Distances are in per mille of the diagonal of the bounding box, without creases → with.",
        "",
    ]
    for target in targets:
        lines += [f"## {target} quads", "", "| Model | Creased edges | of which in part | Hausdorff | Mean distance | Volume kept, % |", "|---|---|---|---|---|---|"]
        for model, _, sharp, _ in MODELS:
            if model not in wanted:
                continue
            for other in list(bpy.data.objects):
                bpy.data.objects.remove(other)
            source = read_obj(source_path(model), model)
            source.data.calc_loop_triangles()
            preset = "hard-surface" if sharp else "organic"
            try:
                mesh, report = openclare.quads_of(source.data, preset, {"quads": target}, creases=True)
            except openclare.engine.EngineError as error:
                lines.append(f"| {model} | — | — | {error} | | |")
                continue
            quads = bpy.data.objects.new(f"{model}.quads", mesh)
            bpy.context.collection.objects.link(quads)
            modifier = quads.modifiers.new("subdivide", "SUBSURF")
            modifier.levels = options.levels
            weights = [item.value for item in mesh.attributes["crease_edge"].data]
            creased = sum(1 for value in weights if value > 0)
            partly = sum(1 for value in weights if 0 < value < 1)

            directory = OUTPUT / "creases"
            directory.mkdir(parents=True, exist_ok=True)
            with_path, without_path = directory / f"{model}_{target}_creased.obj", directory / f"{model}_{target}_smooth.obj"
            subdivided(quads, options.levels, with_path)
            mesh.attributes["crease_edge"].data.foreach_set("value", [0.0] * len(weights))
            mesh.update()
            subdivided(quads, options.levels, without_path)
            smooth, sharpened = measured(source_path(model), without_path), measured(source_path(model), with_path)
            if not smooth or not sharpened:
                lines.append(f"| {model} | {creased} | {partly} | not measured | | |")
                continue

            def pair(key, scale, digits):
                a, b = smooth.get(key), sharpened.get(key)
                return "—" if a is None or b is None else f"{a * scale:.{digits}f} → {b * scale:.{digits}f}"

            row = f"| {model} | {creased} | {partly} | {pair('hausdorff', 1000, 2)} | {pair('mean_distance', 1000, 3)} | {pair('volume_ratio', 100, 2)} |"
            lines.append(row)
            print(row, flush=True)
        lines.append("")
    RESULTS.mkdir(exist_ok=True)
    (RESULTS / "CREASES.md").write_text("\n".join(lines))
    print(f"written: {RESULTS / 'CREASES.md'}")


main()
